class MockTraceFsApiWithBadCperData : public PublicTraceFsApi {
  public:
    static inline const std::string *badDataPtr = nullptr;
    static inline size_t badDataReadPos = 0;
    static inline int eagainCallCount = 0;
    static inline bool shouldFailOpen = false;
    static constexpr int mockBadDataFd = 201;
    static inline const std::string emptyStr{};
    static constexpr size_t midLineBreakPos = 40u;
    static constexpr size_t cperRawBreakOffset = sizeof("cper_raw=AB CD") - 1;

    MockTraceFsApiWithBadCperData(const std::string &eventData = emptyStr, bool failOpen = false, const std::string *tracePipeData = nullptr, bool failTraceRead = false)
        : eventData(eventData), failTraceRead(failTraceRead) {
        loadEntryPointsFromBase();
        shouldFailOpen = failOpen;
        badDataPtr = tracePipeData ? tracePipeData : &this->eventData;
        badDataReadPos = 0;
        eagainCallCount = 0;
    }

    char *traceFsInstanceFileRead(struct tracefs_instance *instance, const char *file, int *psize) override {
        if (failTraceRead) {
            return nullptr;
        }
        if (file && std::string(file) == "trace") {
            if (psize) {
                *psize = static_cast<int>(eventData.size());
            }
            char *result = static_cast<char *>(malloc(eventData.size() + 1));
            memcpy(result, eventData.c_str(), eventData.size() + 1);
            return result;
        }
        return nullptr;
    }

    static int mockSysCallsOpen(const char *pathname, int /*flags*/) {
        if (!shouldFailOpen && pathname && std::string(pathname).find("trace_pipe") != std::string::npos) {
            badDataReadPos = 0;
            eagainCallCount = 0;
            return mockBadDataFd;
        }
        errno = EIO;
        return -1;
    }

    static ssize_t mockSysCallsRead(int fd, void *buf, size_t count) {
        if (fd == mockBadDataFd && badDataPtr != nullptr) {
            if (badDataReadPos >= badDataPtr->size()) {
                return 0;
            }
            size_t bytesToRead = std::min(count, badDataPtr->size() - badDataReadPos);
            memcpy(buf, badDataPtr->data() + badDataReadPos, bytesToRead);
            badDataReadPos += bytesToRead;
            return static_cast<ssize_t>(bytesToRead);
        }
        return 0;
    }

    static ssize_t mockSysCallsReadError(int fd, void *buf, size_t count) {
        if (fd == mockBadDataFd) {
            return -1;
        }
        return 0;
    }

    static ssize_t mockSysCallsReadWithInitialEagain(int fd, void *buf, size_t count) {
        if (fd == mockBadDataFd && eagainCallCount == 0) {
            eagainCallCount++;
            errno = EAGAIN;
            return -1;
        }
        return mockSysCallsRead(fd, buf, count);
    }

    static ssize_t mockSysCallsReadWithEagainMidLine(int fd, void *buf, size_t count) {
        if (fd == mockBadDataFd && eagainCallCount == 0 && badDataReadPos >= midLineBreakPos) {
            eagainCallCount++;
            errno = EAGAIN;
            return -1;
        }
        return mockSysCallsRead(fd, buf, count);
    }

    static ssize_t mockSysCallsReadWithHardErrorMidCperRaw(int fd, void *buf, size_t count) {
        if (fd == mockBadDataFd && badDataPtr != nullptr && eagainCallCount == 0) {
            size_t cperRawPos = badDataPtr->find("cper_raw=");
            if (cperRawPos != std::string::npos && badDataReadPos >= cperRawPos + cperRawBreakOffset) {
                eagainCallCount++;
                size_t nextLinePos = badDataPtr->find('\n', badDataReadPos);
                badDataReadPos = (nextLinePos == std::string::npos) ? badDataPtr->size() : nextLinePos + 1;
                errno = EIO;
                return -1;
            }
        }
        return mockSysCallsRead(fd, buf, count);
    }

    static int mockSysCallsClose(int fd) {
        if (fd == mockBadDataFd) {
            badDataPtr = nullptr;
        }
        return 0;
    }

  private:
    const std::string &eventData;
    bool failTraceRead = false;
};

