class MockTraceFsApiWithBadCperData : public PublicTraceFsApi {
  public:
    static inline const std::string *badDataPtr = nullptr;
    static inline size_t badDataReadPos = 0;
    static inline bool shouldFailOpen = false;
    static constexpr int mockBadDataFd = 201;
    static inline const std::string emptyStr{};

    MockTraceFsApiWithBadCperData(const std::string &eventData = emptyStr, bool failOpen = false, const std::string *tracePipeData = nullptr, bool failTraceRead = false)
        : eventData(eventData), failTraceRead(failTraceRead) {
        loadEntryPointsFromBase();
        shouldFailOpen = failOpen;
        badDataPtr = tracePipeData ? tracePipeData : &this->eventData;
        badDataReadPos = 0;
    }

    char *traceFsInstanceFileRead(struct tracefs_instance *instance, const char *file, int *psize) override {
        if (failTraceRead) {
            return nullptr;
        }
        if (file && std::string(file) == "trace") {
            if (psize) {
                *psize = static_cast<int>(eventData.size());
            }
            char *result = static_cast<char *>(malloc(eventData.size() + 1));
            memcpy(result, eventData.c_str(), eventData.size() + 1);
            return result;
        }
        return nullptr;
    }

    static int mockSysCallsOpen(const char *pathname, int /*flags*/) {
        if (!shouldFailOpen && pathname && std::string(pathname).find("trace_pipe") != std::string::npos) {
            badDataReadPos = 0;
            return mockBadDataFd;
        }
        errno = EIO;
        return -1;
    }

    static ssize_t mockSysCallsRead(int fd, void *buf, size_t count) {
        if (fd == mockBadDataFd && badDataPtr != nullptr) {
            if (badDataReadPos >= badDataPtr->size()) {
                return 0;
            }
            size_t bytesToRead = std::min(count, badDataPtr->size() - badDataReadPos);
            memcpy(buf, badDataPtr->data() + badDataReadPos, bytesToRead);
            badDataReadPos += bytesToRead;
            return static_cast<ssize_t>(bytesToRead);
        }
        return 0;
    }

    static int mockSysCallsClose(int fd) {
        if (fd == mockBadDataFd) {
            badDataPtr = nullptr;
        }
        return 0;
    }

  private:
    const std::string &eventData;
    bool failTraceRead = false;
};

// The trace_pipe reader works on a FILE*, so the fake descriptor above needs a fake stream too.
// fgets() is served one byte at a time through whichever sysCallsRead mock the test installed, which
// keeps every read behaviour (EAGAIN, hard error, end of data) visible to the code under test.
class MockBadCperStdio {
  public:
    static constexpr intptr_t mockFilePtrKey = 0xbadf11e;

    static int mockSysCallsDup(int oldfd) {
        return oldfd;
    }

    static FILE *mockSysCallsFdopen(int fd, const char * /*mode*/) {
        return (fd == MockTraceFsApiWithBadCperData::mockBadDataFd) ? asFile() : nullptr;
    }

    static int mockSysCallsSetvbuf(FILE *stream, char * /*buf*/, int /*mode*/, size_t /*size*/) {
        return (stream == asFile()) ? 0 : -1;
    }

    static int mockSysCallsFclose(FILE *stream) {
        return (stream == asFile()) ? 0 : -1;
    }

    // Mirrors glibc: a stream which merely ran dry (EAGAIN) still hands out the characters collected
    // so far, while any other read failure discards them, and nothing collected always reads as null.
    static char *mockSysCallsFgets(char *s, int size, FILE *stream) {
        if (stream != asFile() || size <= 1) {
            return nullptr;
        }
        std::string line;
        int errorNum = 0;
        while (line.size() + 1 < static_cast<size_t>(size)) {
            char character = 0;
            errno = 0;
            ssize_t bytesRead = NEO::SysCalls::read(MockTraceFsApiWithBadCperData::mockBadDataFd, &character, 1);
            if (bytesRead < 0) {
                errorNum = (errno != 0) ? errno : EIO;
                break;
            }
            if (bytesRead == 0) {
                break; // No data left, so the line ends here
            }
            line += character;
            if (character == '\n') {
                break;
            }
        }

        if (line.empty() || (errorNum != 0 && errorNum != EAGAIN)) {
            errno = errorNum;
            return nullptr;
        }
        errno = 0;
        memcpy(s, line.c_str(), line.size() + 1);
        return s;
    }

  private:
    static FILE *asFile() {
        return reinterpret_cast<FILE *>(mockFilePtrKey);
    }
};

