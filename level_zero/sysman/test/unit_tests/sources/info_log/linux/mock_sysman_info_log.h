// Single mock covering every tracefs behaviour an individual test needs to tweak. The trace data is
// picked with the constructor, and each knob switches exactly one tracefs call over to the failure or
// edge behaviour under test, so tests do not have to derive their own mocks.
class MockTraceFsApiWithConfigurableBehavior : public MockTraceFsApiWithData {
  public:
    static inline struct tracefs_instance *traceReadInstance = nullptr;
    static inline uint32_t traceReadCallCount = 0;
    static inline uint32_t traceOnCallCount = 0;
    // fgets() returns a zero-length, but non-null, line on this call index. trace_pipe can hand out
    // such a read, so the extraction loop has to cope with it both while accumulating a record and
    // while resynchronizing after an overlong one. Zero means never.
    static inline uint32_t emptyLineOnFgetsCall = 0;
    static inline uint32_t fgetsCallCount = 0;

    bool failGetBufferSize = false;
    bool failSetBufferSize = false;
    bool failSetBufferPercent = false;
    bool failGetFile = false;
    bool failTraceFileRead = false;
    // When set, the buffer size query mirrors libtracefs: cpu -1 reports the sum across all CPUs
    // ('buffer_total_size_kb') while cpu >= 0 reports a single per-CPU buffer
    // ('per_cpu/cpuN/buffer_size_kb'), so tests can tell the two queries apart.
    bool reportDistinctPerCpuAndTotalBufferSize = false;
    static constexpr long long mockCpuCountForBufferSize = 8;
    static constexpr long long mockPerCpuBufferSizeKb = 512;
    static constexpr long long mockTotalBufferSizeKb = mockPerCpuBufferSizeKb * mockCpuCountForBufferSize;
    // When set, the tracepoint enable file reads back with this content instead of being absent.
    const char *eventEnableStateContent = nullptr;
    // When set, the tracing_on file reads back with this content instead of being absent.
    const char *tracingOnStateContent = nullptr;

    MockTraceFsApiWithConfigurableBehavior(const std::string &traceData = "", uint32_t emptyLineOnFgetsCallIndex = 0)
        : MockTraceFsApiWithData(false, false, traceData) {
        traceReadInstance = nullptr;
        traceReadCallCount = 0;
        traceOnCallCount = 0;
        emptyLineOnFgetsCall = emptyLineOnFgetsCallIndex;
        fgetsCallCount = 0;
    }

    int traceFsTraceOn(struct tracefs_instance *instance) override {
        traceOnCallCount++;
        return MockTraceFsApiWithData::traceFsTraceOn(instance);
    }

    long long traceFsInstanceGetBufferSize(struct tracefs_instance *instance, int cpu) override {
        if (failGetBufferSize) {
            return -1;
        }
        if (reportDistinctPerCpuAndTotalBufferSize) {
            return (cpu < 0) ? mockTotalBufferSizeKb : mockPerCpuBufferSizeKb;
        }
        return MockTraceFsApiWithData::traceFsInstanceGetBufferSize(instance, cpu);
    }

    int traceFsInstanceSetBufferSize(struct tracefs_instance *instance, size_t size, int cpu) override {
        if (failSetBufferSize) {
            return -1;
        }
        return MockTraceFsApiWithData::traceFsInstanceSetBufferSize(instance, size, cpu);
    }

    int traceFsInstanceSetBufferPercent(struct tracefs_instance *instance, int val) override {
        if (failSetBufferPercent) {
            return -1;
        }
        return MockTraceFsApiWithData::traceFsInstanceSetBufferPercent(instance, val);
    }

    char *traceFsInstanceGetFile(struct tracefs_instance *instance, const char *file) override {
        if (failGetFile) {
            return nullptr;
        }
        return MockTraceFsApiWithData::traceFsInstanceGetFile(instance, file);
    }

    char *traceFsInstanceFileRead(struct tracefs_instance *instance, const char *file, int *psize) override {
        if (file != nullptr && std::string(file) == "events/xe/xe_error_cper/enable" && eventEnableStateContent != nullptr) {
            return strdup(eventEnableStateContent);
        }
        if (file != nullptr && std::string(file) == "tracing_on" && tracingOnStateContent != nullptr) {
            return strdup(tracingOnStateContent);
        }
        if (file != nullptr && std::string(file) == "trace") {
            traceReadInstance = instance;
            traceReadCallCount++;
            if (failTraceFileRead) {
                return nullptr;
            }
        }
        return MockTraceFsApiWithData::traceFsInstanceFileRead(instance, file, psize);
    }

    static char *mockSysCallsFgets(char *s, int size, FILE *stream) {
        if (stream != reinterpret_cast<FILE *>(static_cast<intptr_t>(mockFilePtrKey))) {
            return nullptr;
        }
        fgetsCallCount++;
        if (fgetsCallCount == emptyLineOnFgetsCall) {
            s[0] = '\0';
            return s;
        }
        return MockTraceFsApiWithData::mockSysCallsFgets(s, size, stream);
    }
};

